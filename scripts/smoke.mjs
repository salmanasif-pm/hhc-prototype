await step('office: review, approve, batch, export, pay', async () => {
  await switchTo('office', 'Sam Patel - Billing Specialist');
  await page.goto(BASE + '/office/billing');
  await page.waitForSelector('text=Awaiting review');
  await page.locator('tr:has-text("Delacroix") button:has-text("Review")').click();
  await page.waitForSelector('text=Clinician pay rate');
  const txt = await page.locator('.drawer').innerText();
  if (!txt.includes('$120.00') || !txt.includes('$165.00')) throw new Error('expected clinician $120 and agency $165 rates: ' + txt.slice(0, 200));
  await shot('13-billing-review');
  await page.click('.drawer button:has-text("Approve")');
  await page.waitForSelector('text=both rates snapshotted');
  await page.goto(BASE + '/office/billing/agency');
  await page.waitForSelector('text=Prepare an agency invoice batch');
  await page.locator('button:has-text("Create invoice batch")').click();
  await page.waitForSelector('text=Invoice batch created');
  const [download] = await Promise.all([page.waitForEvent('download'), page.locator('button:has-text("Export file for QuickBooks")').first().click()]);
  const path = await download.path();
  const csv = fs.readFileSync(path, 'utf8');
  console.log('   csv first lines:\n   ' + csv.split('\r\n').slice(0, 2).join('\n   '));
  if (!csv.startsWith('InvoiceNo,Customer') || !csv.includes('Bayside Home Health') || !csv.includes('165.00')) throw new Error('unexpected csv');
  await page.waitForSelector('text=Exported');
  await shot('14-agency-export');
  await page.goto(BASE + '/office/billing/payments');
  await page.locator('tr:has-text("Delacroix") button:has-text("Update")').click();
  await page.locator('.modal select').selectOption('paid');
  await page.locator('.modal input[type=text], .modal input:not([type])').last().fill('ACH 88301');
  await page.click('.modal button:has-text("Save status")');
  await page.waitForSelector('text=Payout status updated');
  await shot('15-payments');
});
