// End-to-end walkthrough of both experiences against a running preview (npm run preview).
// Requires: npm i -D playwright && npx playwright install chromium. Screenshots land in smoke-shots/.
import { chromium } from 'playwright';
import fs from 'node:fs';
const BASE = (process.env.BASE_URL ?? 'http://localhost:4173') + '/#';
const shots = new URL('../smoke-shots/', import.meta.url).pathname;
fs.mkdirSync(shots, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
const shot = (n) => page.screenshot({ path: `${shots}/${n}.png`, fullPage: false });
const step = async (name, fn) => { try { await fn(); console.log('✓', name); } catch (e) { console.log('✗', name, '-', e.message.split('\n')[0]); await shot('FAIL-' + name.replace(/\W+/g, '_')); throw e; } };
const switchTo = async (role, userLabel) => {
  await page.click('.demo-fab');
  const sel = role === 'office' ? page.locator('.demo-panel select').nth(0) : page.locator('.demo-panel select').nth(1);
  await sel.selectOption({ label: userLabel });
  await page.waitForTimeout(300);
};

await step('entry screen renders', async () => {
  await page.goto(BASE + '/');
  await page.waitForSelector('text=One application. Two ways in.');
  await shot('01-entry');
});
await step('office: enter as Maya Chen', async () => {
  await page.selectOption('#office-persona', 'u_maya');
  await page.click('text=Open the office experience');
  await page.waitForSelector('text=Request Management');
  await shot('02-office-requests');
});
await step('office: add patient and referral', async () => {
  await page.click('text=Patient', { timeout: 5000 });
  await page.waitForSelector('text=Patients');
  await page.click('text=Add patient & referral');
  await page.waitForSelector('text=Add patient and referral');
  const f = async (label, value) => { const el = page.locator(`.field:has(label:has-text("${label}")) input, .field:has(label:has-text("${label}")) textarea`).first(); await el.fill(value); };
  await f('First name', 'Rosa'); await f('Last name', 'Delacroix'); await f('Date of birth', '1949-04-12'); await f('MRN', 'BHH-20555'); await f('Phone', '(510) 555-0399'); await f('Street address', '4400 Central Ave, Apt 3'); await f('ZIP', '94536');
  await page.locator('.field:has(label:has-text("Notes to clinicians")) textarea').fill('PT SOC this week. Spanish speaking.');
  await page.locator('.field:has(label:has-text("Case-management notes")) textarea').fill('PT SOC after knee replacement.');
  await shot('03-new-patient');
  await page.click('text=Save and create visit request');
  await page.waitForSelector('text=New visit request');
});
await step('office: request info → select clinicians', async () => {
  await page.waitForSelector('text=Rosa Delacroix');
  await page.click('text=Next: select clinicians');
  await page.waitForSelector('text=Eligible clinicians');
  await shot('04-select-clinicians');
  const rows = await page.locator('.cand-row').count();
  if (rows < 2) throw new Error('expected candidates for PT in 94536');
  const blocked = await page.locator('.cand-row.blocked').count();
  if (blocked < 1) throw new Error('Daniel Okafor should be shown as credential-blocked');
  const disabledChecked = await page.locator('.cand-row.blocked input:disabled').count();
  if (disabledChecked < 1) throw new Error('blocked clinician checkbox should be disabled');
  await page.click('text=Next: review');
  await page.waitForSelector('text=Selected clinicians');
  await shot('05-review-send');
  await page.click('button:has-text("Send request")');
  await page.waitForSelector('text=Request log');
  await shot('06-request-detail-pending');
});
